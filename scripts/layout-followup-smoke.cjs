const assert=require('node:assert/strict')
const {resolve}=require('node:path')
module.exports=async({desktop,page,artifacts})=>{
 const original=await page.evaluate(()=>window.mediaCenter.experience())
 await page.getByRole('button',{name:'Customize collections',exact:true}).click()
 const toggle=page.getByLabel('Show Playlists directly below Home',{exact:true})
 await toggle.check();await page.getByRole('button',{name:'Save collection controls',exact:true}).click()
 await page.waitForFunction(async()=> (await window.mediaCenter.experience()).navigation.playlistsBelowHome)
 const order=await page.locator('.sidebar-scroll>.nav-item').allTextContents()
 assert.equal(order[0].trim(),'Home');assert.equal(order[1].trim(),'Playlists')
 const settingsWidth=await page.locator('.settings-search').evaluate(el=>({width:el.getBoundingClientRect().width,parent:el.parentElement.clientWidth}))
 assert.ok(Math.abs(settingsWidth.width-settingsWidth.parent)<3,'Settings search fills its content width')
 await page.screenshot({path:resolve(artifacts,'settings-full-width-1.2.png')})
 await page.evaluate(async()=>{const a=window.mediaCenter,s=(await a.settings()).connections.find(c=>c.provider==='navidrome');await a.playlistSave({serverId:s.id,name:'Layout test playlist',comment:'',public:false,songIds:['song']})})
 await page.locator('.sidebar-scroll>.nav-item').filter({hasText:'Playlists'}).click()
 await page.getByRole('button',{name:/Layout test playlist/}).click()
 await require('./collection-header-smoke.cjs')(page,artifacts,'single-row-playlist')
 const actions=page.locator('.detail-heading>.listen-actions')
 assert.equal(await actions.locator(':scope>button,:scope>.more-options').count(),5)
 await actions.getByRole('button',{name:'More options',exact:true}).click()
 await page.getByRole('button',{name:'Edit playlist',exact:true}).click()
 await page.getByRole('dialog',{name:'Edit playlist',exact:true}).waitFor()
 await page.getByRole('button',{name:'Close dialog',exact:true}).click()
 await actions.getByRole('button',{name:'More options',exact:true}).click();await page.keyboard.press('ArrowDown');await page.keyboard.press('Escape')
 assert.equal(await actions.getByRole('button',{name:'More options',exact:true}).getAttribute('aria-expanded'),'false')
 await page.getByLabel('Playlist source',{exact:true}).selectOption('local')
 await page.getByRole('heading',{name:'Playlists',exact:true}).waitFor()
 await page.locator('.local-collection-card').first().waitFor()
 for(const name of ['Audiobooks','Podcasts']){
  await page.getByRole('button',{name,exact:true}).click()
  assert.equal(await page.locator('.continue-shelf').count(),0,'All books/shows has no duplicated Continue listening section')
  await page.getByRole('button',{name:'Continue listening',exact:true}).click()
  await page.locator('.continue-grid .resume-card').first().waitFor()
  assert.equal(await page.locator('.continue-grid-section .home-shelf-track').count(),0)
  const cardGeometry=await page.locator('.continue-grid .resume-card').evaluateAll(cards=>cards.map(c=>{const p=c.querySelector('p').getBoundingClientRect(),meter=c.querySelector('.daily-meter').getBoundingClientRect();return p.height>0&&p.bottom<meter.top}))
  assert.ok(cardGeometry.every(Boolean),'Grid card subtitles do not collide with progress')
  await page.screenshot({path:resolve(artifacts,`continue-grid-${name.toLowerCase()}-1.2.png`)})
 }
 await page.getByRole('button',{name:'Library tools',exact:true}).click();await page.getByRole('tab',{name:'People',exact:true}).click()
 const fields=await page.locator('.people-search input,.people-search select,.people-search>.primary').evaluateAll(els=>els.map(e=>e.getBoundingClientRect().bottom))
 assert.ok(Math.max(...fields)-Math.min(...fields)<2,'People form controls share a baseline')
 await page.screenshot({path:resolve(artifacts,'people-alignment-1.2.png')})
 await page.reload();assert.equal((await page.evaluate(()=>window.mediaCenter.experience())).navigation.playlistsBelowHome,true)
 await page.getByRole('button',{name:'Collapse sidebar',exact:true}).click()
 const shortcut=page.locator('.sidebar-scroll>.nav-item').filter({has:page.locator('span',{hasText:'Playlists'})})
 assert.equal(await shortcut.getAttribute('title'),'Playlists')
 await page.evaluate(n=>window.mediaCenter.saveNavigation({action:'collections',collections:n.collections,collectionOrder:n.collectionOrder,queueBelowHome:n.queueBelowHome,playlistsBelowHome:n.playlistsBelowHome}),original.navigation)
 await page.evaluate(n=>window.mediaCenter.saveNavigation({action:'sidebar',collapsed:n.sidebarCollapsed}),original.navigation)
 console.log('Layout follow-up passed: single-row header actions, More menu and dialog, continuation grids, People alignment, full-width Settings and persisted server/local playlist shortcut.')
}
