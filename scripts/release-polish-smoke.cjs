const assert=require('node:assert/strict')
const {resolve}=require('node:path')
module.exports=async({desktop,page,artifacts})=>{
  await page.getByRole('button',{name:'Settings',exact:true}).click()
  const search=page.getByRole('textbox',{name:'Search settings',exact:true})
  await search.waitFor()
  await page.getByLabel('Connection name',{exact:true}).fill('Unsaved connection draft')
  await search.fill('exclusive audio')
  await page.locator('.settings-search-results button').filter({hasText:'Exclusive audio output'}).click()
  await page.locator('.setting-found').waitFor()
  assert.equal(await page.getByLabel('Connection name',{exact:true}).inputValue(),'Unsaved connection draft','Search navigation preserves unsaved fields')
  assert.equal(await page.getByLabel('Exclusive audio output',{exact:true}).evaluate(el=>el===document.activeElement),true)
  await search.fill('discord')
  assert.ok(await page.locator('.settings-search-results button').count()>0)
  await search.fill('no setting like this')
  await page.getByText('No matching settings. Try audio, theme, downloads or Discord.',{exact:true}).waitFor()
  await search.press('Escape')
  await page.getByRole('button',{name:'What’s new',exact:true}).click()
  await page.getByRole('dialog',{name:'What’s new in Media Center 1.0.0',exact:true}).waitFor()
  assert.equal(await page.locator('.release-highlights article').count(),4)
  await page.screenshot({path:resolve(artifacts,'whats-new-1.0.png')})
  await page.getByRole('button',{name:'Search Settings',exact:true}).click()
  await search.waitFor()
  const initial=await page.evaluate(()=>document.documentElement.dataset.theme)
  await page.setViewportSize({width:1600,height:1000})
  for(const scale of [1,1.25,1.5,2]){
    await desktop.evaluate(({BrowserWindow},scale)=>BrowserWindow.getAllWindows()[0].webContents.setZoomFactor(scale),scale)
    await page.evaluate(()=>document.querySelector('.workspace').scrollTop=0)
    await search.fill('equalizer')
    await page.locator('.settings-search-results button').first().waitFor()
    assert.equal(await page.locator('.workspace').evaluate(el=>el.scrollWidth>el.clientWidth),false,`Settings fit at ${scale*100}% scaling`)
    assert.equal(await page.locator('.player-bar').evaluate(el=>el.scrollWidth>el.clientWidth),false,`Player fits at ${scale*100}% scaling`)
    await page.screenshot({path:resolve(artifacts,`settings-scale-${scale*100}.png`)})
    await search.press('Escape')
    await page.getByRole('button',{name:'What’s new',exact:true}).click()
    assert.equal(await page.getByRole('dialog').evaluate(el=>el.scrollWidth>el.clientWidth),false)
    await page.getByRole('button',{name:'Keep listening',exact:true}).click()
  }
  await desktop.evaluate(({BrowserWindow})=>BrowserWindow.getAllWindows()[0].webContents.setZoomFactor(1))
  await page.setViewportSize({width:1440,height:940})
  await page.evaluate(t=>document.documentElement.dataset.theme=t,initial)
  await search.fill('theme')
  await page.screenshot({path:resolve(artifacts,'settings-search-1.0.png')})
  await search.press('Escape')
  await page.getByRole('button',{name:'Local music',exact:true}).click()
  await page.getByRole('button',{name:'Choose music folder',exact:true}).waitFor()
  await page.screenshot({path:resolve(artifacts,'local-empty-1.0.png')})
  await page.getByRole('button',{name:'Music',exact:true}).click()
  assert.equal((await page.evaluate(()=>window.mediaCenter.releaseNews('get'))).unread,false)
  console.log('1.0 polish: Settings search/focus/draft retention, release highlights, empty state and 100/125/150/200% interface scaling passed.')
}
