const assert=require('node:assert/strict');const {resolve}=require('node:path')
module.exports=async({page,artifacts})=>{
 await page.evaluate(async()=>{const a=window.mediaCenter,p=await a.playback(),q=p.queue[0];await a.queueEdit({action:'append',items:[{...q,title:'Upcoming fixture one'},{...q,title:'Upcoming fixture two'}]})})
 await page.getByRole('button',{name:'Open now playing',exact:true}).click()
 for(const width of [2560,1440,1008]){
  await page.setViewportSize({width,height:940})
  const geometry=await page.locator('.expanded-player').evaluate(el=>{const r=el.getBoundingClientRect(),main=el.closest('main').getBoundingClientRect(),w=el.closest('.workspace').getBoundingClientRect();return {width:r.width,available:w.width,left:r.left-main.left,gap:w.width-r.width,radius:getComputedStyle(el).borderRadius,overflow:el.scrollWidth-el.clientWidth}})
  assert.ok(Math.abs(geometry.gap)<2&&Math.abs(geometry.left)<2&&geometry.radius==='0px'&&geometry.overflow<2,JSON.stringify(geometry))
  await page.screenshot({path:resolve(artifacts,`now-playing-canvas-${width}.png`)})
 }
 await page.getByRole('button',{name:'Select',exact:true}).click()
 await page.getByRole('checkbox',{name:'Select queue item 2',exact:true}).check()
 await page.getByRole('checkbox',{name:'Select queue item 3',exact:true}).check()
 await page.getByRole('button',{name:'Remove selected',exact:true}).click()
 await page.waitForFunction(async()=>(await window.mediaCenter.playback()).queue.length===1)
 await page.locator('.undo-toast').getByRole('button',{name:'Undo',exact:true}).click()
 await page.waitForFunction(async()=>(await window.mediaCenter.playback()).queue.length===3)
 await page.waitForFunction(()=>document.querySelectorAll('.queue-row').length===3)
 await page.getByRole('button',{name:'Select',exact:true}).click()
 const seek=page.getByRole('slider',{name:'Playback position',exact:true});await seek.hover()
 await page.locator('.seek-preview').waitFor()
 await page.getByRole('button',{name:'Search all collections',exact:true}).click()
 const input=page.getByPlaceholder('Search across your sources…');await input.fill('Original');await input.press('Enter')
 await page.locator('.global-search-results button').first().waitFor()
 await input.press('ArrowDown')
 assert.ok(await page.evaluate(()=>!!document.activeElement.closest('.global-search-results')))
 await page.keyboard.press('Escape')
 await page.getByRole('button',{name:'Search all collections',exact:true}).click()
 assert.ok(await page.locator('.recent-searches').getByRole('button',{name:'Original',exact:true}).isVisible())
 await page.locator('.recent-searches').getByRole('button',{name:'Clear',exact:true}).click()
 assert.equal(await page.locator('.recent-searches').count(),0)
 await page.keyboard.press('Escape')
}
