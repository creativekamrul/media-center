const assert=require('node:assert/strict')
const {resolve}=require('node:path')
module.exports=async({desktop,page,artifacts})=>{
 const original=await page.evaluate(()=>window.mediaCenter.preferences())
 const bounds=await desktop.evaluate(({BrowserWindow})=>BrowserWindow.getAllWindows()[0].getBounds())
 await desktop.evaluate(({BrowserWindow})=>{const w=BrowserWindow.getAllWindows()[0];w.showInactive();w.focus()})
 await page.getByRole('button',{name:'Maximize window',exact:true}).click()
 await page.getByRole('button',{name:'Restore window',exact:true}).waitFor()
 assert.equal(await desktop.evaluate(({BrowserWindow})=>BrowserWindow.getAllWindows()[0].isMaximized()),true)
 await page.getByRole('button',{name:'Restore window',exact:true}).click()
 await page.getByRole('button',{name:'Maximize window',exact:true}).waitFor()
 assert.equal(await desktop.evaluate(({BrowserWindow})=>BrowserWindow.getAllWindows()[0].isMaximized()),false)
 await page.getByRole('button',{name:'Minimize window',exact:true}).click()
 assert.equal(await desktop.evaluate(({BrowserWindow})=>BrowserWindow.getAllWindows()[0].isMinimized()),true)
 await desktop.evaluate(({BrowserWindow})=>{const w=BrowserWindow.getAllWindows()[0];w.restore();w.showInactive();w.focus()})
 assert.equal(await page.locator('.window-drag-area').evaluate(el=>getComputedStyle(el).getPropertyValue('-webkit-app-region')),'drag')
 assert.equal(await page.locator('.window-controls>button').first().evaluate(el=>getComputedStyle(el).getPropertyValue('-webkit-app-region')),'no-drag')
 assert.equal(await page.evaluate(()=>window.mediaCenter.windowControl('invalid').then(()=>false,()=>true)),true)
 for(const theme of ['forest','charcoal','glass','midnight','ocean','rose','lavender','ember','coffee','nord','monochrome','aubergine','black-glass']){
  await page.evaluate(theme=>document.documentElement.dataset.theme=theme,theme)
  const match=await page.locator('.window-titlebar').evaluate(el=>{const p=document.createElement('div');p.style.background='var(--panel)';el.append(p);const same=getComputedStyle(p).backgroundColor===getComputedStyle(el).backgroundColor;p.remove();return same})
  assert.equal(match,true,'Title bar follows '+theme)
 }
 await page.evaluate(p=>window.mediaCenter.savePreferences({...p,closeToTray:true}),original)
 await page.getByRole('button',{name:'Close window',exact:true}).click()
 assert.equal(await desktop.evaluate(({BrowserWindow})=>BrowserWindow.getAllWindows()[0].isVisible()),false,'Close respects tray preference')
 await desktop.evaluate(({BrowserWindow})=>{const w=BrowserWindow.getAllWindows()[0];w.showInactive();w.focus()})
 await page.evaluate(p=>window.mediaCenter.savePreferences({...p,closeToTray:false}),original)
 await desktop.evaluate(({BrowserWindow})=>{globalThis.__closeSeen=false;globalThis.__closeProbe=e=>{e.preventDefault();globalThis.__closeSeen=true};BrowserWindow.getAllWindows()[0].on('close',globalThis.__closeProbe)})
 await page.getByRole('button',{name:'Close window',exact:true}).click()
 assert.equal(await desktop.evaluate(()=>globalThis.__closeSeen),true,'Close uses the native close lifecycle')
 await desktop.evaluate(({BrowserWindow})=>{BrowserWindow.getAllWindows()[0].removeListener('close',globalThis.__closeProbe);delete globalThis.__closeProbe;delete globalThis.__closeSeen})
 await page.evaluate(p=>window.mediaCenter.savePreferences(p),original)
 await page.evaluate(()=>window.mediaCenter.fullscreen('toggle'))
 await page.locator('.window-titlebar').waitFor({state:'hidden'})
 await page.evaluate(()=>window.mediaCenter.fullscreen('exit'))
 await page.locator('.window-titlebar').waitFor({state:'visible'})
 await desktop.evaluate(({BrowserWindow},bounds)=>BrowserWindow.getAllWindows()[0].setBounds(bounds),bounds)
 await page.setViewportSize({width:1440,height:940})
 await page.getByRole('button',{name:'Open now playing',exact:true}).click()
 const header=page.locator('.now-playing-header')
 await header.getByRole('button',{name:'Close now playing',exact:true}).waitFor()
 assert.equal(await page.locator('.expanded-art .collapse-player').count(),0)
 assert.equal(await header.getByRole('button',{name:'Immersive view',exact:true}).count(),1)
 await page.screenshot({path:resolve(artifacts,'window-chrome-1.0.1.png')})
 await header.getByRole('button',{name:'Close now playing',exact:true}).click()
 assert.equal(await page.locator('.expanded-player').count(),0)
 console.log('Window chrome passed: native minimize/maximize/restore, theme colors, drag exclusions, fullscreen and close/tray lifecycle; grouped player navigation.')
}
