const assert=require('node:assert/strict');const {resolve}=require('node:path')
module.exports=async({page,artifacts})=>{
 const nav=name=>page.locator('.sidebar').getByRole('button',{name,exact:true}).click()
 await nav('Settings')
 assert.equal(await page.locator('.app-style-choice').count(),5)
 assert.equal(await page.locator('.theme-picker').count(),0)
 for(const [name,id] of [['Original','default'],['Slate','precision'],['Paper','editorial'],['Frosted','frosted'],['Liquid Glass','liquid']]){
  await page.getByRole('button',{name:`${name} style`,exact:true}).click()
  await page.getByRole('button',{name:'Save appearance',exact:true}).click()
  await page.waitForFunction(id=>document.documentElement.dataset.appStyle===id,id)
  assert.equal(await page.locator('.settings-unsaved').count(),0)
  await nav('Home');await page.setViewportSize({width:1440,height:940})
  await page.screenshot({path:resolve(artifacts,`consistency-style-${id}.png`)})
  await nav('Music');await page.getByRole('button',{name:'Albums',exact:true}).last().click()
  await page.locator('.music-card').first().click();await page.locator('.detail-hero').waitFor()
  assert.equal(await page.locator('.selection-bar[data-selected=false]>.listen-actions').isVisible(),false)
  await page.getByRole('checkbox',{name:'Select all tracks',exact:true}).check()
  assert.ok(await page.locator('.selection-bar>.listen-actions').isVisible())
  await page.locator('.detail-heading').getByRole('button',{name:'More options',exact:true}).click()
  await page.keyboard.press('End');assert.ok(await page.locator(':popover-open button').last().evaluate(el=>el===document.activeElement))
  await page.keyboard.press('Escape');assert.equal(await page.locator(':popover-open').count(),0)
  await page.setViewportSize({width:1008,height:720})
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'No narrow layout overflow')
  await page.screenshot({path:resolve(artifacts,`consistency-details-${id}-narrow.png`)})
  await page.getByRole('button',{name:'Open now playing',exact:true}).click()
  await page.locator('.now-header-actions').waitFor()
  for(const button of await page.locator('.now-header-actions button.now-view-button').all())assert.equal(await button.evaluate(el=>getComputedStyle(el).borderRadius),'10px','Now Playing uses the shared button corners')
  assert.equal(await page.locator('.expanded-player .queue-row strong').first().evaluate(el=>getComputedStyle(el).color),'rgb(245, 245, 247)','Track text stays readable over the dark listening background, including Paper')
  await page.screenshot({path:resolve(artifacts,`consistency-now-${id}.png`)})
  await page.getByRole('button',{name:'Close now playing',exact:true}).click()
  await nav('Settings')
 }
 // A draft survives leaving Settings, without being silently saved.
 const before=await page.evaluate(()=>window.mediaCenter.preferences())
 await page.getByRole('button',{name:'Paper style',exact:true}).click()
 await nav('Home');assert.equal(await page.evaluate(()=>document.documentElement.dataset.appStyle),'liquid')
 await nav('Settings');await page.locator('.settings-unsaved').waitFor()
 assert.equal(await page.evaluate(()=>document.documentElement.dataset.appStyle),'editorial')
 assert.deepEqual(await page.evaluate(()=>window.mediaCenter.preferences()),before)
 await page.getByRole('button',{name:'Discard changes',exact:true}).click()
 await page.locator('.listening-preferences summary').click()
 const shortcut=page.getByRole('textbox',{name:'search shortcut',exact:true})
 const originalShortcut=await shortcut.inputValue()
 await shortcut.press('Control+Shift+Y')
 await page.getByRole('button',{name:'Discard daily-use changes',exact:true}).click()
 await page.waitForFunction(value=>document.querySelector('[aria-label="search shortcut"]').value===value,originalShortcut)
 const settingsSearch=page.getByRole('textbox',{name:'Search settings',exact:true})
 await settingsSearch.fill('Custom theme CSS');await settingsSearch.press('Enter')
 assert.ok(await page.locator('.advanced-appearance').evaluate(el=>el.open),'Settings search opens the advanced section for its result')
 await nav('Music');await page.getByRole('button',{name:'Albums',exact:true}).last().click()
 await page.getByRole('textbox',{name:'Search music',exact:true}).fill('Test')
 await page.getByLabel('Album sort',{exact:true}).selectOption('byYear')
 await page.waitForTimeout(400)
 await nav('Home');await nav('Music')
 assert.equal(await page.getByRole('textbox',{name:'Search music',exact:true}).inputValue(),'Test')
 assert.equal(await page.getByLabel('Album sort',{exact:true}).inputValue(),'byYear')
 await page.getByRole('textbox',{name:'Search music',exact:true}).fill('');await page.waitForTimeout(400)
 await page.locator('.music-card').last().scrollIntoViewIfNeeded()
 const previous=await page.locator('.workspace').evaluate(el=>el.scrollTop)
 await nav('Home');await nav('Music');await page.locator('.music-card').last().waitFor()
 await page.waitForFunction(y=>Math.abs(document.querySelector('.workspace').scrollTop-y)<3,previous)
 for(const section of ['Audiobooks','Podcasts','Local music']){
  await nav(section)
  const search=section==='Local music'?page.getByPlaceholder('Search titles, albums, artists or genres…'):page.getByRole('textbox',{name:'Search library',exact:true})
  await search.fill(section==='Local music'?'studio':'Test');await page.waitForTimeout(350)
  await nav('Home');await nav(section)
  assert.equal(await search.inputValue(),section==='Local music'?'studio':'Test',`${section} restores its own search`)
  await search.fill('')
 }
 await page.setViewportSize({width:1440,height:940})
 console.log('Consistency pass: five palettes, menus, responsive details, contextual selection, unsaved drafts, filters and scroll restoration passed.')
}
