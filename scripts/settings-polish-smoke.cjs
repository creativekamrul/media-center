const assert=require('node:assert/strict')
const {resolve}=require('node:path')
const {writeFileSync}=require('node:fs')
module.exports=async({desktop,page,artifacts})=>{
 console.log('Settings polish: starting navigation, theme and CSS checks')
 const original=await page.evaluate(()=>window.mediaCenter.preferences())
 await page.getByRole('button',{name:'Settings',exact:true}).click()
 await page.getByRole('button',{name:'Save theme',exact:true}).waitFor()
 const rail=page.getByRole('navigation',{name:'Settings sections'})
 assert.equal(await rail.getByRole('button').count(),6)
 await page.emulateMedia({reducedMotion:'reduce'})
 await rail.getByRole('button',{name:'Appearance',exact:true}).click()
 await page.waitForFunction(()=>document.querySelector('.settings-rail [aria-current]')?.textContent==='Appearance')
 await page.locator('#settings-playback').evaluate(el=>el.scrollIntoView({block:'start',behavior:'instant'}))
 await page.waitForFunction(()=>document.querySelector('.settings-rail [aria-current]')?.textContent==='Playback')
 await page.getByLabel('ReplayGain',{exact:true}).selectOption('album')
 await page.getByRole('button',{name:'Ocean',exact:true}).click()
 await page.getByRole('button',{name:'Save theme',exact:true}).click()
 await page.waitForFunction(async()=>{const p=await window.mediaCenter.preferences();return p.theme==='ocean'&&p.replayGain==='album'})
 await page.getByRole('button',{name:'Rose',exact:true}).click()
 await page.getByLabel('ReplayGain',{exact:true}).selectOption('track')
 await page.getByRole('button',{name:'Save audio preferences',exact:true}).click()
 await page.waitForFunction(async()=>{const p=await window.mediaCenter.preferences();return p.theme==='rose'&&p.replayGain==='track'})
 for(const name of ['Forest','Charcoal','Glass','Midnight','Ocean','Rose','Lavender','Ember','Coffee','Nord','Monochrome','Aubergine','Black Glass']){
  await page.getByRole('button',{name,exact:true}).click()
  await page.waitForFunction(id=>document.documentElement.dataset.theme===id,name.toLowerCase().replace(' ','-'))
  for(const style of ['Gradient','Solid']) {
   await page.getByRole('button',{name:style,exact:true}).click()
   await page.waitForFunction(style=>document.documentElement.dataset.surfaceStyle===style,style.toLowerCase())
   const background=await page.evaluate(()=>{const el=document.createElement('div');el.className='home-feature';document.body.append(el);const bg=getComputedStyle(el).backgroundImage;el.remove();return bg})
   assert.equal(background.includes('gradient'),style==='Gradient',name+' '+style+' finish')
  }
  const panel=await page.locator('#settings-servers .settings-panel').first().evaluate(el=>({background:getComputedStyle(el).backgroundColor,blur:getComputedStyle(el).backdropFilter,expected:getComputedStyle(document.documentElement).getPropertyValue('--panel').trim()}))
  if(name.includes('Glass'))assert.match(panel.blur,/blur/)
  else assert.equal(panel.background,await page.evaluate(color=>{const el=document.createElement('div');el.style.color=color;document.body.append(el);const rgb=getComputedStyle(el).color;el.remove();return rgb},panel.expected))
 }
 for(const width of [1024,1440,1920]){
  await page.setViewportSize({width,height:940})
  await rail.getByRole('button',{name:'Servers',exact:true}).click()
  assert.equal(await page.locator('.workspace').evaluate(el=>el.scrollWidth>el.clientWidth),false)
  await page.screenshot({path:resolve(artifacts,`settings-polish-${width}.png`)})
 }
 await page.setViewportSize({width:1440,height:940})
 const css=':root { --theme-test: imported; } .settings-group-title { letter-spacing: 1px; }',file=resolve(artifacts,'fixture-theme.css')
 writeFileSync(file,'\uFEFF'+css)
 await desktop.evaluate(({dialog},file)=>{globalThis.__themeDialog=dialog.showOpenDialog;dialog.showOpenDialog=async()=>({canceled:false,filePaths:[file]})},file)
 try{
  await page.evaluate(()=>window.mediaCenter.miniPlayer({action:'open'}))
  const mini=desktop.windows().find(w=>w!==page)||await desktop.waitForEvent('window')
  mini.setDefaultTimeout(20000)
  await mini.waitForLoadState('domcontentloaded')
  await page.getByRole('checkbox',{name:'Translucent panels',exact:true}).check()
  await mini.waitForFunction(()=>document.documentElement.dataset.translucency==='true')
  assert.match(await page.locator('#settings-servers .settings-panel').first().evaluate(el=>getComputedStyle(el).backdropFilter),/blur/)
  await page.getByRole('button',{name:'Save theme',exact:true}).click()
  await page.waitForFunction(async()=>(await window.mediaCenter.preferences()).appearance?.translucency===true)
  await page.getByRole('checkbox',{name:'Translucent panels',exact:true}).uncheck()
  await mini.waitForFunction(()=>document.documentElement.dataset.translucency==='false')
  await page.getByRole('button',{name:'Gradient',exact:true}).click()
  await mini.waitForFunction(()=>document.documentElement.dataset.surfaceStyle==='gradient')
  await page.getByRole('button',{name:'Save theme',exact:true}).click()
  await page.waitForFunction(async()=>(await window.mediaCenter.preferences()).appearance?.surfaceStyle==='gradient')
  await page.getByRole('button',{name:'Solid',exact:true}).click()
  await mini.waitForFunction(()=>document.documentElement.dataset.surfaceStyle==='solid')
  await page.getByRole('button',{name:'Import theme CSS',exact:true}).click()
  await page.waitForFunction(()=>document.getElementById('custom-theme-css')?.textContent.includes('--theme-test'))
  await mini.waitForFunction(()=>document.getElementById('custom-theme-css')?.textContent.includes('--theme-test'))
  assert.notEqual((await page.evaluate(()=>window.mediaCenter.preferences())).customCss,css,'Preview does not persist before Save')
  await page.getByRole('button',{name:'Save theme',exact:true}).click()
  await page.waitForFunction(async()=>!!(await window.mediaCenter.preferences()).customCss)
  assert.equal((await page.evaluate(()=>window.mediaCenter.preferences())).customCss,css)
  assert.equal(await mini.evaluate(()=>window.mediaCenter.fullscreen('toggle').then(()=>false,()=>true)),true,'Mini cannot request fullscreen')
  for(const action of ['get','minimize','maximize','close'])assert.equal(await mini.evaluate(action=>window.mediaCenter.windowControl(action).then(()=>false,()=>true),action),true,'Mini cannot control the main window')
  // The main test window starts hidden; native keyboard input requires focus after
  // opening the visible mini player. Real users already have a focused main window.
  await desktop.evaluate(({BrowserWindow})=>{const main=BrowserWindow.getAllWindows().find(w=>!w.webContents.getURL().includes('mini=1'));main.showInactive();main.focus();main.webContents.focus()})
  await page.bringToFront()
  await page.keyboard.press('F11')
  assert.equal(await desktop.evaluate(({BrowserWindow})=>BrowserWindow.getAllWindows().find(w=>!w.webContents.getURL().includes('mini=1')).isFullScreen()),true)
  await page.keyboard.press('Escape')
  assert.equal(await desktop.evaluate(({BrowserWindow})=>BrowserWindow.getAllWindows().find(w=>!w.webContents.getURL().includes('mini=1')).isFullScreen()),false)
  await page.evaluate(()=>window.mediaCenter.fullscreen('toggle'))
  await page.evaluate(()=>window.mediaCenter.fullscreen('exit'))
  await page.getByRole('button',{name:'Remove custom CSS',exact:true}).click()
  await mini.waitForFunction(()=>!document.getElementById('custom-theme-css'))
  await page.getByRole('button',{name:'Save theme',exact:true}).click()
  await mini.getByRole('button',{name:'Close mini player',exact:true}).click()
 }finally{await desktop.evaluate(({dialog})=>{dialog.showOpenDialog=globalThis.__themeDialog;delete globalThis.__themeDialog})}
 await page.evaluate(p=>window.mediaCenter.savePreferences(p),original)
 await page.emulateMedia({reducedMotion:'no-preference'})
 console.log('Settings polish: six sections, 13 themes, shared saves, CSS preview/removal, mini restrictions and fullscreen passed')
}
