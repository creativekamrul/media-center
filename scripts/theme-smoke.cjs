const assert=require('node:assert/strict')
const {resolve}=require('node:path')
module.exports=async function themeSmoke(page,artifacts){
 const original=await page.evaluate(()=>window.mediaCenter.preferences())
 await page.getByRole('button',{name:'Settings',exact:true}).click()
 await page.locator('.app-style-grid').waitFor()
 await page.locator('.discord-diagnostics').waitFor()
 assert.match(await page.locator('.discord-diagnostics').innerText(),/Connection[\s\S]*Artwork/)
 assert.equal(await page.getByRole('button',{name:'Retry artwork',exact:true}).isDisabled(),true)
 assert.equal((await page.evaluate(()=>window.mediaCenter.discordStatus())).connected,false)
 assert.match(await page.locator('.settings-panel').filter({has:page.locator('.discord-diagnostics')}).innerText(),/Leave the custom ID empty/)
 const discordId=page.getByLabel('Custom Discord Application ID (optional)',{exact:true});assert.match(await discordId.getAttribute('placeholder'),/1546622716554121296/)
 await page.getByLabel('Enable Discord Rich Presence',{exact:true}).check();assert.equal(await page.getByRole('button',{name:'Save Discord preferences',exact:true}).isEnabled(),true);await discordId.fill('invalid');assert.equal(await page.getByRole('button',{name:'Save Discord preferences',exact:true}).isDisabled(),true);await discordId.fill('');await page.getByLabel('Enable Discord Rich Presence',{exact:true}).uncheck()
 await page.locator('.discord-diagnostics').scrollIntoViewIfNeeded()
 await page.screenshot({path:resolve(artifacts,'discord-settings.png')})
 assert.equal(await page.locator('.app-style-choice').count(),5)
 for(const [name,id] of [['Original','default'],['Slate','precision'],['Paper','editorial'],['Frosted','frosted'],['Liquid Glass','liquid']]){
  await page.getByRole('button',{name:name+' style',exact:true}).click()
  await page.getByRole('button',{name:'Save appearance',exact:true}).click()
  await page.waitForFunction(id=>document.documentElement.dataset.appStyle===id,id)
  assert.equal((await page.evaluate(()=>window.mediaCenter.preferences())).appearance.appStyle,id)
  await page.getByRole('button',{name:'Home',exact:true}).click()
  await page.locator('.home-shelf-track[aria-label="Continue listening"]').waitFor()
  assert.equal(await page.locator('.workspace').evaluate(el=>el.scrollWidth>el.clientWidth),false)
  await page.screenshot({path:resolve(artifacts,'theme-'+id+'.png')})
  await page.getByRole('button',{name:'Settings',exact:true}).click()
 }
 await page.evaluate(p=>window.mediaCenter.savePreferences(p),original)
}
