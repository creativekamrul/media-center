const assert=require('node:assert/strict')
const {resolve}=require('node:path')
module.exports=async({page,artifacts})=>{
 await page.getByRole('button',{name:'Open Disc 1',exact:true}).waitFor()
 assert.equal(await page.getByRole('tablist',{name:'Local music views'}).getByRole('tab').count(),9)
 await page.getByRole('button',{name:'Open Disc 1',exact:true}).click()
 await page.locator('.local-library-track').waitFor()
 await page.getByRole('button',{name:'Favorite Local track',exact:true}).click()
 await page.getByRole('tab',{name:'Favorites',exact:true}).click()
 await page.getByRole('button',{name:'Unfavorite Local track',exact:true}).waitFor()
 await page.getByRole('checkbox',{name:'Select Local track',exact:true}).check()
 await page.getByRole('button',{name:'Create playlist (1)',exact:true}).click()
 await page.getByLabel('Local playlist name',{exact:true}).fill('Local test playlist')
 await page.getByRole('button',{name:'Save local playlist',exact:true}).click()
 await page.getByRole('dialog',{name:'Create local playlist',exact:true}).waitFor({state:'hidden'})
 await page.getByRole('tab',{name:'Playlists',exact:true}).click()
 await page.getByRole('button',{name:'Open Local test playlist',exact:true}).click()
 await page.locator('.local-library-track').waitFor()
 await page.screenshot({path:resolve(artifacts,'local-library-playlist.png')})
 await page.getByRole('tab',{name:'Songs',exact:true}).click()
 await page.getByLabel('Search local library',{exact:true}).fill('no such music')
 await page.getByText('No matches in this view.',{exact:false}).waitFor()
 await page.getByLabel('Search local library',{exact:true}).fill('Local track')
 await page.locator('.local-library-track').waitFor()
 for(const width of [1024,1440,1920]){await page.setViewportSize({width,height:940});assert.equal(await page.locator('.workspace').evaluate(el=>el.scrollWidth>el.clientWidth),false)}
 await page.setViewportSize({width:1440,height:940})
 console.log('Local library: recursive albums, favorite, playlist, search and responsive views passed.')
}
