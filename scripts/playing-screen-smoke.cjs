const assert=require('node:assert/strict')
const {resolve}=require('node:path')
module.exports=async function playingScreenSmoke({page,waitPlayback,artifacts}){
 const slider=page.locator('.player-bar input[aria-label="Playback position"]')
 const point=async fraction=>{const b=await slider.boundingBox();return {x:b.x+7+(b.width-14)*fraction,y:b.y+b.height/2}}
 const click=async fraction=>{const p=await point(fraction);await page.mouse.click(p.x,p.y)}
 await click(.25);await waitPlayback(p=>p.status==='paused'&&Math.abs(p.position-150)<1)
 const start=await point(.25),end=await point(.75)
 await page.mouse.move(start.x,start.y);await page.mouse.down();await page.mouse.move(end.x,end.y-45,{steps:8});await page.mouse.up()
 await waitPlayback(p=>p.status==='paused'&&Math.abs(p.position-450)<1)
 await slider.focus();await page.keyboard.press('ArrowLeft');await waitPlayback(p=>p.position<450)
 const beforeCancel=(await page.evaluate(()=>window.mediaCenter.playback())).position
 const cancelled=await point(.2);await page.mouse.move(cancelled.x,cancelled.y);await page.mouse.down()
 await slider.dispatchEvent('pointercancel',{pointerId:1});await page.mouse.up()
 assert.ok(Math.abs(Number(await slider.inputValue())-beforeCancel)<1,'Cancelling restores the playback position')
 // A track change while the pointer is captured must discard the old preview.
 const middle=await point(.5);await page.mouse.move(middle.x,middle.y);await page.mouse.down()
 await page.evaluate(()=>window.mediaCenter.queueEdit({action:'jump',index:1}))
 await waitPlayback(p=>p.queueIndex===1&&p.status==='playing')
 await page.mouse.up();await page.evaluate(()=>window.mediaCenter.command({action:'toggle'}))
 assert.ok(Number(await slider.inputValue())<10,'Old drag position must not follow the next queue item')
 await click(.01);await waitPlayback(p=>p.status==='paused'&&Math.abs(p.position-6)<1)
 await page.getByRole('button',{name:'Immersive view',exact:true}).click()
 await page.getByRole('region',{name:'Immersive playing screen',exact:true}).waitFor()
 await page.getByRole('button',{name:'Second test line',exact:true}).waitFor()
 assert.equal(await page.locator('.lyrics-panel').count(),1)
 assert.equal(await page.locator('.screen-queue-item').count(),2)
 assert.equal(await page.locator('.screen-queue-item[aria-current=true]').count(),1)
 await page.getByText('Appearance',{exact:true}).click()
 await page.getByLabel('Playing screen background',{exact:true}).selectOption('stars')
 await page.getByLabel('Lyric font size',{exact:true}).focus();await page.keyboard.press('End')
 for(let i=0;i<8;i++)await page.keyboard.press('ArrowLeft')
 await page.getByRole('button',{name:'Save appearance',exact:true}).click()
 assert.deepEqual(await page.evaluate(()=>window.mediaCenter.playingScreenPreferences()),{background:'stars',fontSize:48,motion:true})
 await page.getByText('Appearance',{exact:true}).click()
 for(const width of [1024,1440,1920]){
  await page.setViewportSize({width,height:940})
  assert.equal(await page.locator('.immersive-player').evaluate(el=>el.scrollWidth>el.clientWidth),false)
  const stage=await page.locator('.immersive-stage').boundingBox(),queue=await page.locator('.screen-queue').boundingBox()
  assert.ok(queue.x>stage.x+stage.width,'Queue belongs on the right')
 }
 await page.setViewportSize({width:1440,height:940})
 await page.emulateMedia({reducedMotion:'reduce'})
 assert.equal(await page.locator('.ambient-glow').evaluate(el=>getComputedStyle(el).animationName),'none')
 await page.emulateMedia({reducedMotion:'no-preference'})
 await page.screenshot({path:resolve(artifacts,'playing-screen-starlight.png')})
 await page.getByRole('button',{name:'Play queue item 1: Original Audio',exact:true}).click()
 await waitPlayback(p=>p.queueIndex===0&&p.status==='playing');await page.evaluate(()=>window.mediaCenter.command({action:'toggle'}))
 await page.getByRole('button',{name:'Second test line',exact:true}).click();await waitPlayback(p=>Math.abs(p.position-2)<.1)
 await page.getByRole('button',{name:'Classic view',exact:true}).click()
 await page.getByRole('button',{name:'Immersive view',exact:true}).click()
 await page.waitForFunction(()=>document.querySelector('select[aria-label="Playing screen background"]')?.value==='stars')
 assert.equal(await page.getByLabel('Playing screen background',{exact:true}).inputValue(),'stars')
 await page.getByRole('button',{name:'Classic view',exact:true}).click()
 assert.equal(await page.locator('.sidebar').evaluate(el=>el.inert),false)
 console.log('Playing screen: first-click seek, captured drag, keyboard seek, track reset, lyrics/queue layout and saved appearance passed.')
}
