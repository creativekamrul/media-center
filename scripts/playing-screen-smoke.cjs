const assert=require('node:assert/strict')
const {resolve}=require('node:path')
module.exports=async function playingScreenSmoke({page,waitPlayback,artifacts}){
 const slider=page.locator('.player-bar input[aria-label="Playback position"]')
 const point=async fraction=>{const b=await slider.boundingBox();return {x:b.x+7+(b.width-14)*fraction,y:b.y+b.height/2}}
 const click=async fraction=>{const p=await point(fraction);await page.mouse.click(p.x,p.y)}
 await click(.25);await waitPlayback(p=>p.status==='paused'&&Math.abs(p.position-150)<1)
 const start=await point(.25),end=await point(.75)
 await page.mouse.move(start.x,start.y);await page.mouse.down();await page.mouse.move(end.x,end.y-45,{steps:8});await page.mouse.up()
 await waitPlayback(p=>p.status==='paused'&&Math.abs(p.position-450)<1)
 await slider.focus();await page.keyboard.press('ArrowLeft');await waitPlayback(p=>p.position<450)
 const beforeCancel=(await page.evaluate(()=>window.mediaCenter.playback())).position
 const cancelled=await point(.2);await page.mouse.move(cancelled.x,cancelled.y);await page.mouse.down()
 await slider.dispatchEvent('pointercancel',{pointerId:1});await page.mouse.up()
 assert.ok(Math.abs(Number(await slider.inputValue())-beforeCancel)<1,'Cancelling restores the playback position')
 // A track change while the pointer is captured must discard the old preview.
 const middle=await point(.5);await page.mouse.move(middle.x,middle.y);await page.mouse.down()
 await page.evaluate(()=>window.mediaCenter.queueEdit({action:'jump',index:1}))
 await waitPlayback(p=>p.queueIndex===1&&p.status==='playing')
 await page.mouse.up();await page.evaluate(()=>window.mediaCenter.command({action:'toggle'}))
 assert.ok(Number(await slider.inputValue())<10,'Old drag position must not follow the next queue item')
 await click(.01);await waitPlayback(p=>p.status==='paused'&&Math.abs(p.position-6)<1)
 await page.getByRole('button',{name:'Immersive view',exact:true}).click()
 await page.getByRole('region',{name:'Immersive playing screen',exact:true}).waitFor()
 assert.ok(await page.locator('.screen-cover').evaluate(el=>{const r=el.getBoundingClientRect(),radius=parseFloat(getComputedStyle(el).borderTopLeftRadius);return Math.abs(r.width-r.height)<2&&radius>0&&radius<r.width/4}),'Immersive artwork is a rounded square')
 await page.locator('.screen-track').screenshot({path:resolve(artifacts,'immersive-rounded-cover.png')})
 await page.getByRole('button',{name:'Second test line',exact:true}).waitFor()
 assert.equal(await page.locator('.lyrics-panel').count(),1)
 assert.equal(await page.locator('.immersive-stage .lyrics-tools').count(),0)
 await page.locator('.immersive-header summary').filter({hasText:'Lyrics tools'}).click()
 await page.screenshot({path:resolve(artifacts,'immersive-lyric-tools.png')})
 await page.locator('.immersive-header').getByRole('button',{name:'Find lyrics',exact:true}).click()
 await page.getByRole('dialog').waitFor()
 assert.equal(await page.locator('.immersive-stage [role=dialog]').count(),0)
 await page.getByRole('dialog').getByRole('button',{name:'Close dialog',exact:true}).click()
 await page.getByRole('button',{name:'Show Now Playing',exact:true}).click()
 await page.locator('.immersive-stage .spoken-stage').waitFor()
 await page.screenshot({path:resolve(artifacts,'immersive-music-now-playing.png')})
 assert.equal(await page.locator('.immersive-stage .lyrics-panel').count(),0)
 assert.equal((await page.evaluate(()=>window.mediaCenter.playingScreenPreferences())).showMusicLyrics,false)
 await page.getByRole('button',{name:'Classic view',exact:true}).click()
 await page.getByRole('button',{name:'Immersive view',exact:true}).click()
 await page.getByRole('button',{name:'Show lyrics',exact:true}).click()
 await page.getByRole('button',{name:'Second test line',exact:true}).waitFor()

 assert.equal(await page.locator('.screen-queue-item').count(),2)
 assert.equal(await page.locator('.screen-queue-item[aria-current=true]').count(),1)
 await page.getByText('Appearance',{exact:true}).click()
 await page.getByLabel('Playing screen background',{exact:true}).selectOption('stars')
 await page.getByLabel('Lyric font size',{exact:true}).focus();await page.keyboard.press('End')
 for(let i=0;i<8;i++)await page.keyboard.press('ArrowLeft')
 await page.getByLabel('Lyric font',{exact:true}).selectOption('georgia')
 await page.getByLabel('Animation style',{exact:true}).selectOption('focus')
 await page.getByLabel('Current word color',{exact:true}).fill('#ffb86b')
 await page.screenshot({path:resolve(artifacts,'lyrics-appearance-popup.png')})
 await page.getByRole('button',{name:'Save appearance',exact:true}).click()
 await page.getByRole('dialog',{name:'Lyrics appearance',exact:true}).waitFor({state:'hidden'})
 const saved=await page.evaluate(()=>window.mediaCenter.playingScreenPreferences())
 assert.equal(saved.background,'stars');assert.equal(saved.fontSize,48);assert.equal(saved.wordColor,'#ffb86b');assert.equal(saved.font,'georgia');assert.equal(saved.animation,'focus')
 await page.getByText('Appearance',{exact:true}).click()
 await page.getByRole('button',{name:'Reset appearance',exact:true}).click()
 assert.equal(await page.locator('.immersive-player').evaluate(el=>getComputedStyle(el).getPropertyValue('--lyric-word')),'#b9e8ff')
 await page.getByRole('button',{name:'Cancel',exact:true}).click()
 assert.equal(await page.locator('.immersive-player').evaluate(el=>getComputedStyle(el).getPropertyValue('--lyric-word')),'#ffb86b')
 assert.deepEqual(await page.evaluate(()=>window.mediaCenter.playingScreenPreferences()),saved)
 // Modal stays on screen at narrow sizes, traps keyboard focus, and Escape cancels.
 await page.getByText('Appearance',{exact:true}).click()
 await page.setViewportSize({width:700,height:720})
 assert.equal(await page.locator('.lyrics-appearance').evaluate(el=>el.scrollWidth>el.clientWidth),false)
 await page.getByRole('button',{name:'Save appearance',exact:true}).focus();await page.keyboard.press('Tab')
 assert.equal(await page.locator('.lyrics-appearance').evaluate(el=>el.contains(document.activeElement)),true)
 await page.keyboard.press('Escape')
 await page.getByRole('dialog',{name:'Lyrics appearance',exact:true}).waitFor({state:'hidden'})
 for(const width of [1024,1440,1920]){
  await page.setViewportSize({width,height:940})
  assert.equal(await page.locator('.immersive-player').evaluate(el=>el.scrollWidth>el.clientWidth),false)
  const stage=await page.locator('.immersive-stage').boundingBox(),queue=await page.locator('.screen-queue').boundingBox()
  assert.ok(queue.x>stage.x+stage.width,'Queue belongs on the right')
 }
 await page.setViewportSize({width:1440,height:940})
 await page.emulateMedia({reducedMotion:'reduce'})
 assert.equal(await page.locator('.ambient-glow').evaluate(el=>getComputedStyle(el).animationName),'none')
 await page.emulateMedia({reducedMotion:'no-preference'})
 await page.screenshot({path:resolve(artifacts,'playing-screen-starlight.png')})
 await page.getByRole('button',{name:'Play queue item 1: Original Audio',exact:true}).click()
 await waitPlayback(p=>p.queueIndex===0&&p.status==='playing');await page.evaluate(()=>window.mediaCenter.command({action:'toggle'}))
 await page.getByRole('button',{name:'Second test line',exact:true}).click();await waitPlayback(p=>Math.abs(p.position-2)<.1)
 await page.evaluate(()=>window.mediaCenter.command({action:'seek',value:3.5}))
 await waitPlayback(p=>p.status==='paused'&&Math.abs(p.position-3.5)<.1)
 await page.waitForFunction(()=>document.querySelectorAll('.immersive-stage .karaoke.active [data-word-state=past]').length===1&&document.querySelectorAll('.immersive-stage .karaoke.active [data-word-state=active]').length===1)
 assert.match(await page.locator('.immersive-stage .karaoke.active [data-word-state=active]').evaluate(el=>getComputedStyle(el).backgroundImage),/255, 184, 107/)
 assert.match(await page.locator('.immersive-stage .lyric-line.current').evaluate(el=>getComputedStyle(el).fontFamily),/Georgia/)
 await page.waitForFunction(()=>{const s=getComputedStyle(document.querySelector('.immersive-stage .lyric-line.current'));return Number(s.opacity)===1&&(s.filter==='none'||s.filter==='blur(0px)')})
 await page.screenshot({path:resolve(artifacts,'lyrics-focus-words.png')})
 await page.getByRole('button',{name:'Classic view',exact:true}).click()
 await page.getByRole('button',{name:'Immersive view',exact:true}).click()
 await page.getByText('Appearance',{exact:true}).click()
 await page.waitForFunction(()=>document.querySelector('select[aria-label="Playing screen background"]')?.value==='stars')
 assert.equal(await page.getByLabel('Playing screen background',{exact:true}).inputValue(),'stars')
 assert.equal(await page.getByLabel('Current word color',{exact:true}).inputValue(),'#ffb86b')
 await page.getByRole('button',{name:'Cancel',exact:true}).click()
 await page.getByRole('button',{name:'Classic view',exact:true}).click()
 assert.equal(await page.locator('.sidebar').evaluate(el=>el.inert),false)
 await page.waitForFunction(()=>{const line=document.querySelector('.standard-lyrics .lyric-line.current');return !!line&&getComputedStyle(line).fontFamily.includes('Georgia')})
 assert.equal(await page.locator('.standard-lyrics .lyric-line.current').evaluate(el=>getComputedStyle(el).fontSize),'48px')
 await page.getByRole('button',{name:'Lyrics appearance',exact:true}).click()
 await page.getByLabel('Current word color',{exact:true}).fill('#88ddaa')
 await page.getByRole('button',{name:'Save appearance',exact:true}).click()
 await page.getByRole('dialog',{name:'Lyrics appearance',exact:true}).waitFor({state:'hidden'})
 assert.match(await page.locator('.standard-lyrics .karaoke.active [data-word-state=active]').evaluate(el=>getComputedStyle(el).backgroundImage),/136, 221, 170/)
 await page.screenshot({path:resolve(artifacts,'normal-lyrics-custom.png')})
 await require('./word-lift-smoke.cjs')({page,waitPlayback,artifacts})
 console.log('Playing screen: first-click seek, captured drag, keyboard seek, track reset, lyrics/queue layout and saved appearance passed.')
}
