const {_electron:electron}=require('playwright')
const assert=require('node:assert/strict')
const {resolve}=require('node:path')
const {mkdirSync}=require('node:fs')

async function main(){
  const output=resolve('artifacts/mobile-preview')
  mkdirSync(output,{recursive:true})
  const app=await electron.launch({args:[resolve('mobile/tests/preview-window.cjs'),'--user-data-dir='+resolve(output,'profile-'+Date.now())]})
  try{
    const page=await app.firstWindow()
    const errors=[],external=[]
    page.on('pageerror',e=>errors.push(e.message))
    await page.context().route(/^https?:/,r=>{external.push(r.request().url());return r.abort()})
    await page.setViewportSize({width:390,height:844})
    await page.reload()
    await page.getByRole('heading',{name:'Explore',exact:true}).waitFor()
    await page.evaluate(()=>document.fonts.ready)
    async function shot(name){await page.screenshot({path:resolve(output,name+'.png'),animations:'disabled'})}
    await shot('explore')
    await page.getByRole('button',{name:'Feature Focus Flow',exact:true}).click()
    await page.locator('.featureTitle').click()
    await page.getByRole('heading',{name:'Focus Flow',exact:true}).waitFor()
    await page.getByRole('button',{name:'Back',exact:true}).click()
    assert.equal(await page.locator('.featureTitle').innerText(),'Focus Flow')
    await page.getByRole('button',{name:'Feature Night Transit',exact:true}).click()
    await page.getByRole('button',{name:'Play featured release',exact:true}).click()
    await page.getByRole('button',{name:'Pause preview',exact:true}).click()
    await page.getByRole('button',{name:'Track details',exact:true}).click()
    await page.getByRole('dialog',{name:'Track details'}).waitFor()
    await page.keyboard.press('Escape')
    await page.getByRole('button',{name:'Sleep timer',exact:true}).click()
    await page.getByRole('button',{name:'15 minutes',exact:true}).click()
    await page.getByText('Timer on',{exact:true}).waitFor()
    await shot('player')
    await page.getByRole('button',{name:'Favorite track'}).click()
    await page.getByRole('button',{name:'Lyrics',exact:true}).click()
    await page.getByRole('button',{name:'A quieter kind of time',exact:true}).click()
    assert.ok(Number(await page.getByLabel('Seek position').inputValue())>80)
    await page.getByRole('button',{name:'Up next',exact:true}).click()
    const sheet=page.getByRole('dialog',{name:'Up next'})
    await sheet.getByRole('button',{name:/Harbor Lights/}).waitFor()
    await shot('lyrics-and-queue')
    await page.keyboard.press('Escape')
    await sheet.waitFor({state:'hidden'})
    await page.getByRole('button',{name:'Artwork',exact:true}).click()
    await page.getByRole('button',{name:'Close player',exact:true}).click()
    await page.getByRole('button',{name:'Library',exact:true}).click()
    await page.getByRole('button',{name:'Customize library'}).click()
    await page.getByRole('button',{name:'Move Albums up'}).click()
    assert.equal(await page.locator('.viewSettings>div').first().innerText(),'Albums\n−')
    await page.getByRole('button',{name:'Unpin Podcasts'}).click()
    await page.getByRole('button',{name:'Pin Podcasts',exact:true}).click()
    await page.getByLabel('Typography').selectOption('sora')
    await page.keyboard.press('Escape')
    assert.equal(await page.locator('.groups button').first().innerText(),'Albums')
    await shot('library')
    await page.getByLabel('Library source').selectOption('Downtify')
    await page.getByRole('button',{name:/Focus Flow.*tracks/}).click()
    await page.getByRole('heading',{name:'Focus Flow',exact:true}).waitFor()
    await page.getByRole('button',{name:'Search',exact:true}).click()
    await page.getByPlaceholder('Songs, albums, artists').fill('Northline')
    assert.equal(await page.locator('.trackRow').count(),2)
    await page.getByRole('button',{name:'Home',exact:true}).click()
    await page.getByRole('heading',{name:'Your favorites'}).waitFor()
    await page.setViewportSize({width:320,height:640})
    assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth))
    assert.deepEqual(errors,[])
    assert.deepEqual(external,[])
    console.log('Offline preview passed: album and back, player, timed lyrics, queue sheet, favorites, saved playlists, search and narrow layout.')
  }finally{await app.close()}
}
main().catch(e=>{console.error(e);process.exitCode=1})
